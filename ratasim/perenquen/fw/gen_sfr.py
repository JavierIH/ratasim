"""Perenquen's part header (its repository's p33EP512MC806.h, Microchip's) for the host: every special function
register a word of host memory that the simulated chip (pchip.c) reads and writes, its bit fields over the same word.

    python3 gen_sfr.py PART_HEADER OUT_DIR      writes OUT_DIR/p33Exxxx.h and OUT_DIR/sfr.c

The header keeps the part's typedefs and its `_NAME` bit macros. Each register NAME becomes the word `sim_NAME.w`
(a byte register `.b`), NAMEbits the same storage seen through its bit-field type. The registers in HOOKED are
reached through sim_touch() first: the chip sees every access to them before it happens (the CPU's priority level
for interrupts, the ADC's sample/convert bits), so they can react as the hardware does. The configuration-word
macros (_FOSC(x)...) expand to nothing; the inline-assembler ones to the simulated chip's functions.
"""
import os
import re
import sys

HOOKED = ('SR', 'AD1CON1')
SFR = re.compile(r'^extern volatile (unsigned int|unsigned char|unsigned long|[A-Za-z0-9_]+)\s+([A-Za-z0-9_]+)\s+'
                 r'__attribute__\(\(__sfr__[^;]*;\s*$')
CONFIG = re.compile(r'^(extern __attribute__\(\(space\(prog\)\)\) int _\w+;|#define (_F\w+)\(x\) .*)$')
MEMBER = {'unsigned int': 'w', 'unsigned char': 'b', 'unsigned long': 'l'}


def main(header, out):
    lines = open(header, encoding='latin-1').read().splitlines()
    regs, bits, other = {}, {}, {}
    body = []
    for line in lines:
        m = SFR.match(line)
        if m:
            typ, name = m.groups()
            if typ in MEMBER:
                regs[name] = MEMBER[typ]
            elif name.endswith('bits'):
                bits[name[:-4]] = typ
            else:
                other[name] = typ
            continue
        c = CONFIG.match(line)
        if c:
            if c.group(2):
                body.append(f'#define {c.group(2)}(x)')
            continue
        if line.startswith('#define Nop()') or line.startswith('#define ClrWdt()') or \
           line.startswith('#define Sleep()') or line.startswith('#define Idle()'):
            continue
        body.append(line)
    # the part's own guard and processor check stay; the register declarations go after its typedefs
    end = max(i for i, l in enumerate(body) if l.startswith('#endif'))
    decl = ['', '/* ---- ratasim: the registers in host memory (gen_sfr.py) ---- */',
            'typedef union { unsigned short w; unsigned char b; unsigned long l; unsigned long long pad; } sim_sfr_t;',
            'volatile void *sim_touch(int reg);']
    for i, name in enumerate(HOOKED):
        decl.append(f'#define SIM_REG_{name} {i}')
    for name, member in sorted(regs.items()):
        decl.append(f'extern volatile sim_sfr_t sim_{name};')
        if name in HOOKED:
            decl.append(f'#define {name} (((volatile sim_sfr_t *)sim_touch(SIM_REG_{name}))->{member})')
        else:
            decl.append(f'#define {name} (sim_{name}.{member})')
    for name, typ in sorted(bits.items()):
        if name not in regs:
            decl.append(f'extern volatile sim_sfr_t sim_{name};')
        if name in HOOKED:
            decl.append(f'#define {name}bits (*(volatile {typ} *)sim_touch(SIM_REG_{name}))')
        else:
            decl.append(f'#define {name}bits (*(volatile {typ} *)&sim_{name})')
        decl.append(f'_Static_assert(sizeof({typ}) <= sizeof(sim_sfr_t), "{name}bits");')
    for name, typ in sorted(other.items()):
        decl.append(f'extern volatile {typ} sim_{name};')
        decl.append(f'#define {name} sim_{name}')
    decl += ['#define Nop() do {} while (0)', '#define ClrWdt() do {} while (0)',
             'void sim_cpu_reset(void);', '']
    body[end:end] = decl
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, 'p33Exxxx.h'), 'w') as f:
        f.write('/* Generated by ratasim/perenquen/fw/gen_sfr.py from %s: do not edit. */\n' % os.path.basename(header))
        f.write('\n'.join(body) + '\n')
    with open(os.path.join(out, 'sfr.c'), 'w') as f:
        f.write('/* Generated by ratasim/perenquen/fw/gen_sfr.py: the registers\' storage. */\n#include "p33Exxxx.h"\n')
        for name in sorted(set(regs) | set(bits)):
            f.write(f'volatile sim_sfr_t sim_{name};\n')
        for name, typ in sorted(other.items()):
            f.write(f'volatile {typ} sim_{name};\n')
        f.write('const char *const sim_reg_names[] = {%s};\n' % ', '.join(f'"{n}"' for n in HOOKED))


if __name__ == '__main__':
    main(*sys.argv[1:3])
